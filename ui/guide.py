"""Страница «Инструкция»: пошаговое руководство для менеджера маркетплейса.

Написана простым языком под ежедневную работу: что открыть, что ввести, куда
смотреть и какие решения принимать на каждой странице приложения.
"""
from __future__ import annotations

import streamlit as st


def render() -> None:
    st.title("📘 Инструкция: как пользоваться калькулятором")
    st.caption(
        "Пошаговое руководство для менеджера маркетплейса. Это ваш ежедневный "
        "рабочий инструмент: считайте экономику товара, сравнивайте площадки, "
        "проверяйте риски и держите тарифы в актуальном состоянии."
    )

    st.info(
        "💡 **Главное правило:** слева всегда находится панель «Параметры товара». "
        "Вы заполняете её один раз — и эти данные автоматически используются на "
        "страницах «Калькулятор», «Сравнение МП» и «Сценарии». Менять их можно в любой момент."
    )

    # ---------------------------------------------------------------- Быстрый старт
    st.header("🚀 Быстрый старт за 1 минуту")
    st.markdown(
        """
1. Откройте страницу **«Калькулятор»** (открывается по умолчанию).
2. Слева в панели **«Параметры товара»** введите четыре главных числа:
   - **Цена продажи** — по какой цене покупатель видит товар;
   - **Себестоимость** — во сколько товар обошёлся вам (закупка);
   - **Вес** и **Объём** — с упаковкой (от них зависит логистика).
3. Сверху выберите **Маркетплейс** и **Схему работы** (например, Ozon + FBO).
4. Посмотрите блок **«Итог»**: чистая прибыль, маржинальность, ROI и цена безубыточности.
5. Если видите зелёный значок **«✅ ОТЛИЧНО»** — товар выгоден. Красный **«❌ УБЫТОЧНО»** — нужно менять цену или расходы.

Готово. Ниже — подробно по каждой странице.
        """
    )

    # ---------------------------------------------------------------- Панель слева
    st.header("🧾 Панель «Параметры товара» (слева на всех страницах)")
    st.markdown("Заполняется один раз и действует на всех расчётных страницах. Что означает каждое поле:")
    st.markdown(
        """
| Поле | Что вводить | Подсказка |
|---|---|---|
| **Наименование товара** | Название/артикул для себя | Ни на что не влияет, просто пометка |
| **Цена продажи, ₽** | Цена для покупателя | Основа всех расчётов |
| **Себестоимость, ₽** | Закупочная цена за 1 шт | Сколько вы платите поставщику |
| **Вес, кг** | Вес с упаковкой | Влияет на логистику |
| **Объём, л** | Габариты в литрах | Влияет на логистику и хранение |
| **Категория товара** | Категория на МП | От неё зависит комиссия |
| **Налоговый режим** | Ваша система налогов | УСН, патент, самозанятость и т.д. |
| **ДРР, %** | Доля рекламных расходов | Сколько % от цены уходит на рекламу |
| **Выкуп, %** | Процент выкупа | 85% значит 15 из 100 заказов вернут |
| **Реклама фикс., ₽/шт** | Фикс. реклама на штуку | Если считаете рекламу не в % |
| **Брак/потери, %** | Потери от себестоимости | Бой, порча, пересорт |
| **Доп. себестоимость, ₽/шт** | Упаковка, работа, вложения | Всё, что добавляется к закупке |
| **Срок хранения, дней** | Сколько товар лежит на складе | Для оценки затрат на хранение |
| **Постоянные расходы в месяц, ₽** | Аренда, зарплаты, подписки | Для точки безубыточности в штуках |
        """
    )
    st.success(
        "✅ **Совет на каждый день:** держите «Выкуп %» и «ДРР %» реалистичными — "
        "именно они чаще всего «съедают» прибыль. Берите их из отчётов кабинета продавца."
    )

    st.divider()
    st.header("📄 Подробно по каждой странице")

    tab_calc, tab_cmp, tab_scen, tab_tar, tab_help = st.tabs(
        ["📊 Калькулятор", "⚖️ Сравнение МП", "🎯 Сценарии", "📦 Тарифы", "ℹ️ Справка"]
    )

    # ---------------------------------------------------------------- Калькулятор
    with tab_calc:
        st.subheader("📊 Калькулятор — сердце инструмента")
        st.markdown("**Зачем:** быстро понять, сколько вы зарабатываете на одной единице товара.")
        st.markdown("**Когда использовать:** каждый раз перед выводом товара, сменой цены или при пересчёте акции.")
        st.markdown("**Пошагово:**")
        st.markdown(
            """
1. Заполните панель **«Параметры товара»** слева (см. раздел выше).
2. Вверху выберите **Маркетплейс** и **Схему работы** (FBO — товар на складе МП;
   FBS — на вашем складе; DBS/realFBS — доставка вами).
3. Посмотрите блок **«Итог»** — 4 главные цифры:
   - **Чистая прибыль / шт** — сколько остаётся «в кармане» с одной продажи;
   - **Маржинальность** — доля прибыли в цене (главный показатель здоровья товара);
   - **ROI** — сколько прибыли на каждый вложенный в закупку рубль;
   - **Цена безубыточности** — минимальная цена, ниже которой вы в минусе.
4. Ниже — **«Детализация на единицу»**: строка за строкой видно, куда уходят деньги
   (комиссия, логистика, реклама, хранение, налог, себестоимость).
5. Справа — диаграмма **«Структура расходов»**: сразу видно самую большую статью затрат.
6. В самом низу — таблица **«Сравнение схем поставки»**: какая схема (FBO/FBS/…)
   выгоднее для этого товара.
            """
        )
        st.markdown("**Ручная правка расходов** (раскрывающийся блок «⚙️ Расходы маркетплейса»):")
        st.markdown(
            """
- Если для вашего товара тариф отличается (особый склад, промо-логистика) —
  впишите точные значения вручную. Расчёт сразу обновится.
- Можно **добавлять свои статьи расходов** (например, «Фотосъёмка» или «Штраф»):
  добавьте строку, выберите базу (% от цены / фикс. сумма) и укажите значение.
- Кнопка **«↺ Сбросить к тарифу»** вернёт значения из официального тарифа.
            """
        )
        st.info("🎯 **Как принять решение:** цель — маржинальность обычно ≥ 15–20%. "
                "Если ниже — поднимите цену, снизьте ДРР, смените схему или пересмотрите закупку.")

    # ---------------------------------------------------------------- Сравнение
    with tab_cmp:
        st.subheader("⚖️ Сравнение МП — где продавать выгоднее")
        st.markdown("**Зачем:** один и тот же товар посчитать сразу на всех площадках и выбрать лучшую.")
        st.markdown("**Когда использовать:** при выборе площадки для нового товара или при планировании выхода на новый МП.")
        st.markdown("**Пошагово:**")
        st.markdown(
            """
1. Убедитесь, что панель **«Параметры товара»** слева заполнена (те же данные, что на «Калькуляторе»).
2. Откройте страницу — таблица посчитается автоматически по всем маркетплейсам.
3. Смотрите столбцы: **Чистая прибыль**, **Маржа**, **Расходы МП**, **ROI**, **Цена безубыточности**.
4. Зелёным подсвечены **лучшие значения**. Сверху — подсказка, какая площадка выгоднее всего.
5. Ниже — два графика: **прибыль** и **маржинальность** по площадкам для наглядности.
            """
        )
        st.warning("⚠️ **Важно:** сравнение честное только при актуальных тарифах. "
                   "Если давно не обновляли комиссии — сначала загляните на страницу «Тарифы».")

    # ---------------------------------------------------------------- Сценарии
    with tab_scen:
        st.subheader("🎯 Сценарии — проверка на риски «что если»")
        st.markdown("**Зачем:** понять, что будет с прибылью, если условия изменятся (подорожает логистика, вырастет реклама, упадёт выкуп).")
        st.markdown("**Когда использовать:** при планировании акций, распродаж, перед сезоном или ростом рекламных ставок.")
        st.markdown("**Пошагово:**")
        st.markdown(
            """
1. Выберите **Маркетплейс** и **Схему**.
2. Приложение сразу покажет 4 сценария в таблице:
   - **Базовый** — как есть сейчас;
   - **Оптимистичный** — цена чуть выше, расходы чуть ниже, выкуп выше;
   - **Пессимистичный** — цена ниже, комиссия/реклама/логистика выше, выкуп ниже;
   - **Ручной** — вы задаёте сами ползунками.
3. Настройте **Ручной сценарий** ползунками: множители для цены, комиссии, ДРР,
   логистики, хранения и поправку к выкупу. Например, «×1.3 к ДРР» = реклама выросла на 30%.
4. Сравните строки таблицы: зелёным — лучший результат, красным — худший.
5. На графике видно разброс прибыли между сценариями.
            """
        )
        st.info("🎯 **Как читать:** если даже в пессимистичном сценарии прибыль остаётся "
                "положительной — товар устойчив. Если уходит в минус — закладывайте запас по цене.")

    # ---------------------------------------------------------------- Тарифы
    with tab_tar:
        st.subheader("📦 Тарифы маркетплейсов — держим данные актуальными")
        st.markdown("**Зачем:** маркетплейсы регулярно меняют комиссии и логистику. Здесь вы обновляете их — и все расчёты сразу становятся точными.")
        st.markdown("**Когда использовать:** когда МП объявил новые тарифы, раз в месяц для сверки, или при добавлении новой категории.")
        st.markdown("**Пошагово:**")
        st.markdown(
            """
1. Выберите **Маркетплейс**. Сверху видно **источник** (ссылка) и **дату актуальности**.
2. В блоке **«Общие параметры»** поправьте эквайринг, хранение, обратную логистику.
3. В таблице **«Комиссии по категориям»** измените процент нужной категории или
   добавьте новую строку (кнопкой «+» внизу таблицы).
4. В таблице **«Логистика по схемам»** задайте стоимость доставки: базовая часть,
   доплата за литр и за кг, минимальная стоимость.
5. При необходимости добавьте **дополнительные статьи расходов** (например, «Платная приёмка»).
6. Впишите **комментарий к изменению** (например: «обновил по оферте от 07.2026»).
7. Нажмите **«💾 Сохранить тариф»**. Внизу появится запись в **«Истории изменений»**
   с датой, источником и комментарием — так вы всегда знаете, кто и когда что менял.
            """
        )
        st.success("✅ **Хорошая привычка:** обновляйте тарифы из официального кабинета "
                   "продавца, а в комментарии указывайте дату оферты. Это защищает от ошибок в расчётах.")
        st.warning("⚠️ Значения «из коробки» — ориентировочные. Перед серьёзными решениями "
                   "сверяйте комиссии и логистику с вашим личным кабинетом на маркетплейсе.")

    # ---------------------------------------------------------------- Справка
    with tab_help:
        st.subheader("ℹ️ Справка — формулы и определения")
        st.markdown(
            """
Отдельная страница **«Справка»** — для тех, кто хочет разобраться в «математике»:
- какие формулы используются в расчёте;
- что именно означает каждый показатель (валовая/операционная/чистая прибыль, ROI, ROMI и т.д.);
- как считается точка безубыточности;
- где и как менять тарифы.

Открывайте её, когда нужно понять, **почему** получилась та или иная цифра, или
объяснить расчёт коллеге/руководителю.
            """
        )

    # ---------------------------------------------------------------- Чек-лист
    st.divider()
    st.header("🗓️ Ежедневный чек-лист менеджера")
    st.markdown(
        """
- [ ] **Новый товар?** Посчитайте на «Калькуляторе», затем проверьте на «Сравнении МП».
- [ ] **Меняете цену или запускаете акцию?** Прогоните через «Сценарии» — не уйдёте ли в минус.
- [ ] **МП объявил новые тарифы?** Обновите их на странице «Тарифы» (с комментарием).
- [ ] **Реклама/логистика подорожали?** Обновите ДРР и логистику, пересчитайте маржу.
- [ ] **Выкуп просел?** Поставьте реальный % выкупа из отчёта и посмотрите, как изменилась прибыль.
- [ ] **Готовите отчёт руководителю?** Возьмите цифры из «Итога» и «Сравнения МП».
        """
    )

    # ---------------------------------------------------------------- FAQ
    st.header("❓ Частые вопросы")
    with st.expander("Почему прибыль отрицательная, хотя цена выше себестоимости?"):
        st.write(
            "Кроме закупки есть комиссия МП, логистика (в т.ч. по невыкупленным заказам), "
            "реклама, хранение и налог. Откройте «Детализацию на единицу» на «Калькуляторе» — "
            "увидите, какая статья съедает прибыль."
        )
    with st.expander("Что важнее — маржинальность или чистая прибыль в рублях?"):
        st.write(
            "Смотрите на оба. Маржинальность показывает «здоровье» товара в %, а чистая "
            "прибыль в ₽ — реальный заработок с продажи. Дешёвый товар может иметь высокую "
            "маржу, но копейки прибыли, и наоборот."
        )
    with st.expander("Что такое «Цена безубыточности»?"):
        st.write(
            "Это минимальная цена продажи, при которой вы выходите в ноль (чистая прибыль = 0). "
            "Продавать ниже неё — работать в убыток. Удобно для планирования скидок."
        )
    with st.expander("Влияют ли мои правки тарифов на расчёты?"):
        st.write(
            "Да. Всё приложение построено на данных из тарифов. Обновили комиссию на "
            "странице «Тарифы» — «Калькулятор», «Сравнение» и «Сценарии» сразу считают по новым значениям."
        )
    with st.expander("Как посчитать точку безубыточности в штуках за месяц?"):
        st.write(
            "Заполните поле «Постоянные расходы в месяц» слева (аренда, зарплаты и т.п.). "
            "Тогда в «Ключевых показателях» появится, сколько штук нужно продать в месяц, "
            "чтобы окупить постоянные расходы."
        )
