"""Страница справки: формулы, показатели и порядок обновления тарифов."""
from __future__ import annotations

import streamlit as st


def render() -> None:
    st.title("ℹ️ Справка")

    st.markdown(
        """
### Как работает калькулятор

Приложение построено по принципу **data-driven**: тарифы маркетплейсов хранятся
отдельно от кода (в `data/tariffs/*.json`), а бизнес-логика расчёта не зависит
от конкретных чисел. Это позволяет обновлять условия площадок без переписывания
логики.

**Слои приложения:**
- `data/` — тарифы маркетплейсов (комиссии, логистика, хранение, эквайринг, прочее) с источником и датой;
- `calculators/` — модели и движок расчёта юнит-экономики, сценарии;
- `services/` — загрузка/сохранение тарифов, резолвер параметров;
- `ui/` — интерфейс (страницы Streamlit).

### Основные формулы (на единицу проданного товара)

- **Выкуп** `b`: чтобы продать 1 шт., отгружаем `1/b` шт.; `(1−b)/b` шт. возвращаются.
- **Комиссия** = Цена × Комиссия%
- **Эквайринг** = Цена × Эквайринг%
- **Логистика** = Логистика_туда × (1/b) + (Обратная + Обработка) × ((1−b)/b)
- **Хранение** = Ставка_за_литр_в_день × Объём × Дни
- **Реклама** = Цена × ДРР% + Реклама_фикс
- **Себестоимость** = Закупка + Доп. себестоимость + Брак%
- **Операционная прибыль** = Цена − все расходы (кроме налога)
- **Налог** — по режиму (от выручки или от прибыли)
- **Чистая прибыль** = Операционная прибыль − Налог

### Что означают показатели

| Показатель | Смысл |
|---|---|
| Валовая прибыль | Выручка − себестоимость |
| Операционная прибыль | Прибыль до налога после всех расходов МП и рекламы |
| Чистая прибыль | Итог после налога, на единицу |
| Маржинальность | Чистая прибыль ÷ Цена |
| Наценка / ROI | Чистая прибыль ÷ Себестоимость |
| ROMI | Чистая прибыль ÷ Рекламные затраты |
| Цена безубыточности | Минимальная цена, при которой чистая прибыль = 0 |
| Точка безубыточности, шт | Постоянные расходы ÷ вклад на единицу |

Точка безубыточности по цене вычисляется **численно** (бисекцией), поэтому корректно
работает при любой структуре расходов, включая процентные статьи и налог.

### Где менять тарифы

Страница **«Тарифы маркетплейсов»** — служебный режим: правьте комиссии, логистику,
хранение, эквайринг и дополнительные статьи. Каждое сохранение фиксирует дату,
источник и комментарий в истории версий.

На **главной** странице тарифы можно переопределить вручную под конкретный кейс
(раздел «Расходы маркетплейса — ручная правка»), не меняя сами файлы.

### Официальные источники тарифов

- Ozon Seller — https://seller.ozon.com/
- Wildberries (WB Partners) — https://seller.wildberries.ru/terms
- Яндекс Маркет для партнёров — https://partner.market.yandex.com/

> ⚠️ Значения в поставке — ориентировочные **baseline**. Перед реальными расчётами
> сверяйте ставки с личным кабинетом продавца и публичной офертой площадки.
        """
    )
